create extension if not exists pgcrypto;
create schema if not exists vet;

-- ---------------------------------------------------------------------
-- 1. Tablas
-- ---------------------------------------------------------------------

-- Perfil de cada persona del equipo (uno por usuario que inicia sesión)
create table vet.perfiles (
  id         uuid primary key references auth.users(id) on delete cascade,
  nombre     text not null default '',
  cargo      text not null default 'Médico veterinario',
  registro   text not null default '',
  email      text,
  rol        text not null default 'miembro' check (rol in ('admin', 'miembro')),
  activo     boolean not null default false,   -- un admin debe aprobar a cada persona nueva
  creado_en  timestamptz not null default now()
);

-- Pacientes (mascotas). Los campos de la ficha van en "datos" (JSON)
create table vet.pacientes (
  id              uuid primary key default gen_random_uuid(),
  numero          bigint generated by default as identity unique,  -- N° de ficha correlativo
  nombre          text not null,
  datos           jsonb not null default '{}'::jsonb,
  creado_por      uuid references vet.perfiles(id),
  creado_en       timestamptz not null default now(),
  actualizado_por uuid references vet.perfiles(id),
  actualizado_en  timestamptz not null default now()
);

-- Consultas / atenciones de cada paciente
create table vet.consultas (
  id              uuid primary key default gen_random_uuid(),
  paciente_id     uuid not null references vet.pacientes(id) on delete cascade,
  fecha           date not null,
  proximo_control date,
  medico_id       uuid references vet.perfiles(id),
  datos           jsonb not null default '{}'::jsonb,
  creado_por      uuid references vet.perfiles(id),
  creado_en       timestamptz not null default now(),
  actualizado_por uuid references vet.perfiles(id),
  actualizado_en  timestamptz not null default now()
);
create index consultas_paciente_idx on vet.consultas (paciente_id);
create index consultas_control_idx  on vet.consultas (proximo_control);
create index consultas_creado_idx   on vet.consultas (creado_en desc);

-- Registro de cambios (solo se agregan filas, nunca se editan ni borran)
create table vet.eventos (
  id          bigint generated always as identity primary key,
  paciente_id uuid references vet.pacientes(id) on delete cascade,
  tipo        text not null,
  detalle     text not null default '',
  por         uuid references vet.perfiles(id) default auth.uid(),
  en          timestamptz not null default now()
);
create index eventos_paciente_idx on vet.eventos (paciente_id, en desc);

-- ---------------------------------------------------------------------
-- 2. Funciones de apoyo
-- ---------------------------------------------------------------------

create or replace function vet.es_miembro() returns boolean
language sql stable security definer set search_path = vet, public as $$
  select exists (select 1 from vet.perfiles where id = auth.uid() and activo);
$$;

create or replace function vet.es_admin() returns boolean
language sql stable security definer set search_path = vet, public as $$
  select exists (select 1 from vet.perfiles where id = auth.uid() and activo and rol = 'admin');
$$;

-- La app llama a esta función al iniciar sesión: crea el perfil de la persona
-- (pendiente de aprobación). Solo cuentan quienes entran a la app veterinaria,
-- no los usuarios de otras apps del mismo proyecto.
-- La PRIMERA persona que entra a la app veterinaria queda como administradora.
create or replace function vet.registrarme() returns vet.perfiles
language plpgsql security definer set search_path = vet, public as $$
declare
  u auth.users%rowtype;
  p vet.perfiles%rowtype;
  primero boolean;
begin
  if auth.uid() is null then raise exception 'Sin sesión'; end if;
  select * into p from vet.perfiles where id = auth.uid();
  if found then return p; end if;
  select * into u from auth.users where id = auth.uid();
  perform pg_advisory_xact_lock(4242);
  select not exists (select 1 from vet.perfiles) into primero;
  insert into vet.perfiles (id, nombre, email, rol, activo)
  values (
    u.id,
    coalesce(nullif(u.raw_user_meta_data->>'full_name', ''), nullif(u.raw_user_meta_data->>'name', ''), split_part(u.email, '@', 1)),
    u.email,
    case when primero then 'admin' else 'miembro' end,
    primero
  )
  returning * into p;
  return p;
end;
$$;

-- Quién creó y quién modificó cada registro: lo pone la base de datos,
-- así nadie puede firmar a nombre de otra persona.
create or replace function vet.firmar_registro() returns trigger
language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    new.creado_por := auth.uid();
    new.creado_en  := now();
  else
    new.creado_por := old.creado_por;
    new.creado_en  := old.creado_en;
  end if;
  new.actualizado_por := auth.uid();
  new.actualizado_en  := now();
  return new;
end;
$$;

create trigger firmar_pacientes before insert or update on vet.pacientes
  for each row execute function vet.firmar_registro();
create trigger firmar_consultas before insert or update on vet.consultas
  for each row execute function vet.firmar_registro();

-- Solo un admin puede cambiar el rol o aprobar/desactivar personas.
create or replace function vet.proteger_perfil() returns trigger
language plpgsql security definer set search_path = vet, public as $$
begin
  if (new.rol is distinct from old.rol or new.activo is distinct from old.activo or new.email is distinct from old.email)
     and not vet.es_admin() then
    raise exception 'Solo un administrador puede cambiar el rol o el acceso de una persona';
  end if;
  return new;
end;
$$;

create trigger proteger_perfiles before update on vet.perfiles
  for each row execute function vet.proteger_perfil();

-- ---------------------------------------------------------------------
-- 3. Seguridad por filas (RLS): solo el equipo aprobado ve los datos
-- ---------------------------------------------------------------------

alter table vet.perfiles  enable row level security;
alter table vet.pacientes enable row level security;
alter table vet.consultas enable row level security;
alter table vet.eventos   enable row level security;

-- Perfiles
create policy "ver perfiles"        on vet.perfiles for select using (vet.es_miembro() or id = auth.uid());
create policy "editar mi perfil"    on vet.perfiles for update using (id = auth.uid() or vet.es_admin());

-- Pacientes
create policy "ver pacientes"       on vet.pacientes for select using (vet.es_miembro());
create policy "crear pacientes"     on vet.pacientes for insert with check (vet.es_miembro());
create policy "editar pacientes"    on vet.pacientes for update using (vet.es_miembro());
create policy "borrar pacientes"    on vet.pacientes for delete using (vet.es_admin());

-- Consultas
create policy "ver consultas"       on vet.consultas for select using (vet.es_miembro());
create policy "crear consultas"     on vet.consultas for insert with check (vet.es_miembro());
create policy "editar consultas"    on vet.consultas for update using (vet.es_miembro());
create policy "borrar consultas"    on vet.consultas for delete using (vet.es_admin());

-- Eventos (registro de cambios): se leen y se agregan, no se editan ni borran
create policy "ver eventos"         on vet.eventos for select using (vet.es_miembro());
create policy "agregar eventos"     on vet.eventos for insert with check (vet.es_miembro() and por = auth.uid());

-- ---------------------------------------------------------------------
-- 4. Permisos para que la app pueda usar el schema "vet"
--    (las reglas RLS de arriba siguen decidiendo qué ve cada persona)
-- ---------------------------------------------------------------------
grant usage on schema vet to anon, authenticated;
grant select, insert, update, delete on all tables in schema vet to authenticated;
grant usage, select on all sequences in schema vet to authenticated;
grant execute on function vet.registrarme(), vet.es_miembro(), vet.es_admin() to authenticated;
revoke execute on function vet.registrarme() from anon;

-- ---------------------------------------------------------------------
-- 5. Tiempo real: que todos vean los cambios al instante
-- ---------------------------------------------------------------------
alter publication supabase_realtime add table vet.pacientes, vet.consultas, vet.perfiles;
